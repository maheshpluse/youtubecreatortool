def pretty(d) -> str:
    """'September 7, 2026'. Day is interpolated rather than formatted because
    the no-pad directive is %#d on Windows and %-d elsewhere -- neither is
    portable, and the wrong one silently renders the literal text."""
    if isinstance(d, str):
        d = date.fromisoformat(d)
    return f"{d:%B} {d.day}, {d.year}"


def words(fragment: str) -> int:
    txt = re.sub(r"<[^>]+>", " ", fragment)
    txt = html.unescape(txt)
    return len([w for w in re.split(r"\s+", txt) if w.strip()])


def ad_slot(slot_id: str, label: str) -> str:
    if not (ADSENSE_CLIENT and slot_id):
        return ('\n<!-- Ad slot (%s): add ADSENSE_CLIENT + slot id in '
                'blog_src/build_blog.py and rebuild. -->\n' % label)
    return (
        '\n<div class="ad-slot">\n'
        '  <span class="ad-label">Advertisement</span>\n'
        '  <ins class="adsbygoogle" style="display:block" data-ad-client="%s" '
        'data-ad-slot="%s" data-ad-format="auto" data-full-width-responsive="true"></ins>\n'
        '  <script>(adsbygoogle = window.adsbygoogle || []).push({});</script>\n'
        '</div>\n' % (ADSENSE_CLIENT, slot_id)
    )


