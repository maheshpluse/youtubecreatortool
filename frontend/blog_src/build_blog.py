def dq(v: str) -> str:
    """Escape a Python string for a single-quoted Dart literal."""
    return (v.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$"))


def render_dart(posts):
    rows = []
    for p in posts:
        h = HERO.get(p["slug"])
        img_url = h["svg"].lstrip("../") if h else 'images/blog/%s.jpg' % p["slug"]
        rows.append(
            "  BlogPost(\n"
            "    slug: '%s',\n"
            "    title: '%s',\n"
            "    description: '%s',\n"
            "    category: '%s',\n"
            "    date: '%s',\n"
            "    readMinutes: %d,\n"
            "    imageUrl: '%s',\n"
            "  ),"
            % (dq(p["slug"]), dq(p["title"]), dq(p["description"]),
               dq(p["category"]),
               dq(pretty(p["date"])),
               max(1, round(p["_words"] / 220)),
               dq(img_url))
        )
    body = "\n".join(rows)
    return (
        "// GENERATED FILE - do not edit by hand.\n"
        "// Source: blog_src/posts.json + blog_src/posts/*.html\n"
        "// Regenerate with: python3 blog_src/build_blog.py\n"
        "\n"
        "/// Metadata for one published article under web/blog/.\n"
        "class BlogPost {\n"
        "  final String slug;\n"
        "  final String title;\n"
        "  final String description;\n"
        "  final String category;\n"
        "  final String date;\n"
        "  final int readMinutes;\n"
        "  final String imageUrl;\n"
        "\n"
        "  const BlogPost({\n"
        "    required this.slug,\n"
        "    required this.title,\n"
        "    required this.description,\n"
        "    required this.category,\n"
        "    required this.date,\n"
        "    required this.readMinutes,\n"
        "    required this.imageUrl,\n"
        "  });\n"
        "\n"
        "  /// Path to the standalone, crawlable article page.\n"
        "  String get url => 'blog/$slug.html';\n"
        "}\n"
        "\n"
        "/// Every article, newest first.\n"
        "const List<BlogPost> blogPosts = [\n%s\n];\n" % body
    )


def render_sitemap(posts):
    today = date.today().isoformat()
    urls = [
        (SITE_URL + "/", today, "1.0"),
        (SITE_URL + "/youtube-seo-analyzer", today, "0.9"),
        (SITE_URL + "/youtube-title-generator", today, "0.9"),
        (SITE_URL + "/youtube-thumbnail-ideas", today, "0.9"),
        (SITE_URL + "/youtube-tag-extractor", today, "0.9"),
        (SITE_URL + "/youtube-earnings-calculator", today, "0.9"),
        (SITE_URL + "/youtube-rpm-by-country", today, "0.9"),
        (SITE_URL + "/blog/", today, "0.9"),
        (SITE_URL + "/about", today, "0.6"),
        (SITE_URL + "/contact", today, "0.6"),
        (SITE_URL + "/privacy", today, "0.5"),
        (SITE_URL + "/terms", today, "0.5"),
    ]
    urls += [(f"{SITE_URL}/blog/{p['slug']}.html", p.get("updated", p["date"]), "0.8")
             for p in posts]
    body = "\n".join(
        "  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n"
        "    <changefreq>monthly</changefreq>\n    <priority>%s</priority>\n  </url>"
        % (u, m, pr) for u, m, pr in urls
    )
    ns = "http://www.sitemaps.org/schemas/sitemap/0.9"
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="%s"\n'
            '        xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"\n'
            '        xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd">\n%s\n</urlset>\n' % (ns, body))


