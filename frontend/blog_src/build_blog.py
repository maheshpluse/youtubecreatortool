def render_faq(faq):
    if not faq:
        return ""
    items = "\n".join(
        '  <details><summary>%s</summary><p>%s</p></details>' % (q, a) for q, a in faq
    )
    return '\n<h2 id="faq">Frequently asked questions</h2>\n<div class="faq">\n%s\n</div>\n' % items


def render_endmatter(post):
    # No visible keyword list. A rendered list of target terms at the foot of an
    # article reads as keyword stuffing to both readers and search engines; the
    # terms still travel in the JSON-LD "keywords" property, which is the
    # appropriate place for them.
    src = "\n".join(
        '  <li>%s &mdash; <a href="%s" rel="noopener nofollow" target="_blank">%s</a></li>'
        % (html.escape(t), u, html.escape(u.replace("https://", "")))
        for t, u in post["sources"]
    )
    return f"""
<section class="endmatter">
  <h2>Sources and further reading</h2>
  <ol class="sources">
{src}
  </ol>
</section>"""


def render_related(post, posts):
    i = posts.index(post)
    picks = [posts[(i + n) % len(posts)] for n in (1, 2, 3)]
    cards = "\n".join(
        '    <li class="card"><span class="cat">%s</span>'
        '<h3><a href="/blog/%s.html">%s</a></h3><p>%s</p></li>'
        % (html.escape(p["category"]), p["slug"], html.escape(p["title"]),
           html.escape(p["description"][:110].rsplit(" ", 1)[0] + "…"))
        for p in picks
    )
    return f"""
<section class="related">
  <h2>Keep reading</h2>
  <ul class="card-grid">
{cards}
  </ul>
</section>"""


def json_ld(post):
    url = f"{SITE_URL}/blog/{post['slug']}.html"
    blog_posting = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": post["title"],
        **({"image": [SITE_URL + HERO[post["slug"]]["png"]]} if post["slug"] in HERO else {}),
        "description": post["description"],
        "articleSection": post["category"],
        "keywords": ", ".join(post["keywords"]),
        "wordCount": post["_words"],
        "inLanguage": "en",
        "datePublished": post["date"],
        "dateModified": post.get("updated", post["date"]),
        "mainEntityOfPage": {"@type": "WebPage", "@id": url},
        "url": url,
        "author": {"@type": "Organization", "name": AUTHOR, "url": SITE_URL},
        "publisher": {
            "@type": "Organization",
            "name": SITE_NAME,
            "url": SITE_URL,
            "logo": {"@type": "ImageObject", "url": PUBLISHER_LOGO},
        },
        "isAccessibleForFree": True,
    }
    crumbs = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE_URL},
            {"@type": "ListItem", "position": 2, "name": "Blog", "item": SITE_URL + "/blog/"},
            {"@type": "ListItem", "position": 3, "name": post["title"], "item": url},
        ],
    }
    blocks = [blog_posting, crumbs]
    if post.get("faq"):
        blocks.append({
            "@context": "https://schema.org",
            "@type": "FAQPage",
            "mainEntity": [
                {"@type": "Question", "name": q,
                 "acceptedAnswer": {"@type": "Answer", "text": re.sub(r"<[^>]+>", "", a)}}
                for q, a in post["faq"]
            ],
        })
    return "\n".join(
        '  <script type="application/ld+json">%s</script>'
        % json.dumps(b, ensure_ascii=False, separators=(",", ":")) for b in blocks
    )


